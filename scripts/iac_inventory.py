#!/usr/bin/env python3
"""Read-only inventory of one environment, with a check of the five mandatory tags and of the naming pattern.

1. Resource Groups Tagging API: every resource tagged repo-name=<repository> (any env-type) plus the
   resources tagged env-type=<env> that carry no repo-name but whose name looks like this project's.
2. Kinds the tagging API does not return or that controllers create without the project tags, found through
   the project VPC: security groups and their rules, load balancers, listeners and target groups.
3. Findings: a resource of this project that lacks one of the five tags (or holds a wrong repo-name or
   env-type value) or whose name breaks `<acronym>-<region code>-<context>[-<descriptor>]-<env>`.
   Names generated by AWS services or by the controllers (prefixes below) are exempt from the name rule only.

Usage (the owner runs it after a deployment, with read-only credentials):

    python scripts/iac_inventory.py --env dev [--profile P] [--region us-east-2] [--output report.json]

Exit code 0 when there is no finding, 1 when there are findings, 2 when an AWS read fails. Only list, describe
and get calls are made. Keep the output file outside the repository (it holds resource names).
Not covered: resources that carry no tag and no project VPC (for example an untagged EBS volume) cannot be
found by any read-only call; the destroy check (`post_destroy_check.py`) covers what is left after a teardown.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

REPO_NAME = "over-engineered-simple-calculator-aws-eks-version"
MANDATORY_TAGS = ("team-owner", "project-name", "app-name", "repo-name", "env-type")
# Names that AWS services and the controllers generate; the five tags are still required on them.
GENERATED_NAME_PREFIXES = ("k8s-", "eks-", "rds!", "default", "AWSServiceRole")
# Runtime artifacts and kinds whose name is generated or has no meaning.
SKIPPED_TYPES = {"ec2:network-interface", "rds:snapshot", "rds:auto-backup", "ec2:security-group-rule"}
NAMELESS_TYPES = {
    "ssm:parameter",
    "kms:key",
    "eks:nodegroup",
    "eks:addon",
    "eks:access-entry",
    "eks:podidentityassociation",
    "elasticloadbalancing:listener",
    "elasticloadbalancing:listener-rule",
    "rds:proxy",
    "rds:db-proxy-endpoint",
}
ID_LIKE = re.compile(r"^[a-z]{1,6}-[0-9a-f]{8,}$")
SECRET_SUFFIX = re.compile(r"-[A-Za-z0-9]{6}$")


class ReadError(RuntimeError):
    """An AWS read failed."""


def aws(args: list[str], region: str, profile: str | None) -> dict[str, Any]:
    command = ["aws", *args, "--region", region, "--output", "json"]
    if profile:
        command += ["--profile", profile]
    completed = subprocess.run(command, capture_output=True, text=True, check=False)  # noqa: S603
    if completed.returncode != 0:
        redacted = re.sub(r"\b\d{12}\b", "************", completed.stderr.strip())[:300]
        raise ReadError(f"aws {' '.join(args[:2])} failed: {redacted}")
    data: dict[str, Any] = json.loads(completed.stdout) if completed.stdout.strip() else {}
    return data


def name_pattern(region_code: str, context: str, env: str) -> re.Pattern[str]:
    """`<acronym>-<region code>-<context>[-<descriptor>]-<env>`."""
    return re.compile(rf"^[a-z0-9]+-{re.escape(region_code)}-{re.escape(context)}(-[A-Za-z0-9-]+)?-{re.escape(env)}$")


def resource_type(arn: str) -> str:
    """service:resource-type of an ARN (arn:partition:service:region:account:type/... or type:...)."""
    parts = arn.split(":", 5)
    if len(parts) < 6:
        return "unknown"
    service, rest = parts[2], parts[5]
    kind = re.split(r"[/:]", rest, maxsplit=1)[0]
    return f"{service}:{kind}" if kind != rest else f"{service}:{service}"


def candidate_name(arn: str, tags: dict[str, str]) -> str | None:
    """The name given to the resource, or None when it has no name to check (ids, generated kinds)."""
    if tags.get("Name"):
        return tags["Name"]
    parts = arn.split(":", 5)
    if len(parts) < 6:
        return None
    service, rest = parts[2], parts[5]
    kind = resource_type(arn)
    if service == "ec2" or kind in NAMELESS_TYPES:
        return None
    pieces = rest.split("/")
    if service == "elasticloadbalancing":  # loadbalancer/app/NAME/id, targetgroup/NAME/id
        name = pieces[2] if pieces[0] == "loadbalancer" and len(pieces) > 2 else pieces[1] if len(pieces) > 1 else ""
    elif service == "logs":  # log-group:NAME[:*]
        name = rest.partition(":")[2].removesuffix(":*")
    elif service == "secretsmanager":  # secret:NAME-xxxxxx
        name = SECRET_SUFFIX.sub("", rest.partition(":")[2])
    elif service == "s3" or kind == f"{service}:{service}":  # arn:aws:s3:::NAME, arn:aws:sqs:r:a:NAME
        name = rest
    else:  # type/NAME, type:NAME or type/path/NAME
        name = re.split(r"[/:]", rest, maxsplit=1)[1] if re.search(r"[/:]", rest) else rest
        name = name.split("/")[-1] if service == "iam" else name
    name = name.rstrip("/")
    return None if not name or ID_LIKE.match(name) else name


def name_is_valid(name: str, pattern: re.Pattern[str]) -> bool:
    segments = [s for s in name.removeprefix("alias/").split("/") if s]
    if any(name.startswith(prefix) or s.startswith(prefix) for prefix in GENERATED_NAME_PREFIXES for s in segments):
        return True
    return any(pattern.match(s) for s in segments)


def tag_problems(tags: dict[str, str], env: str, repo_name: str) -> list[str]:
    problems = [f"missing tag {key}" for key in MANDATORY_TAGS if not tags.get(key)]
    if tags.get("repo-name") and tags["repo-name"] != repo_name:
        problems.append(f"repo-name is {tags['repo-name']}")
    if tags.get("env-type") and tags["env-type"] != env:
        problems.append(f"env-type is {tags['env-type']}")
    return problems


def as_tags(pairs: list[dict[str, str]] | None) -> dict[str, str]:
    return {t["Key"]: t["Value"] for t in pairs or [] if not t["Key"].startswith("aws:")}


def tagged_resources(a: argparse.Namespace) -> list[dict[str, Any]]:
    """Resources of this repository, plus partially tagged ones of this environment that look like ours."""
    found: dict[str, dict[str, Any]] = {}
    for key, value in (("repo-name", a.repo_name), ("env-type", a.env)):
        data = aws(
            ["resourcegroupstaggingapi", "get-resources", "--tag-filters", f"Key={key},Values={value}"],
            a.region,
            a.profile,
        )
        for mapping in data.get("ResourceTagMappingList", []):
            arn = mapping["ResourceARN"]
            tags = as_tags(mapping.get("Tags"))
            if resource_type(arn) in SKIPPED_TYPES:
                continue
            if key == "repo-name" and tags.get("env-type", a.env) != a.env:
                continue  # another environment of this repository
            name = candidate_name(arn, tags) or ""
            if key == "env-type" and (tags.get("repo-name") or f"-{a.context}-eks-" not in f"-{name}-"):
                continue  # another project's resource, or not recognizable as ours
            found[arn] = {"arn": arn, "type": resource_type(arn), "name": name or None, "tags": tags}
    return sorted(found.values(), key=lambda r: (r["type"], r["arn"]))


def vpc_id_of(resources: list[dict[str, Any]]) -> str | None:
    for item in resources:
        if item["type"] == "ec2:vpc":
            return str(item["arn"].rsplit("/", 1)[-1])
    return None


def elb_tags(arns: list[str], region: str, profile: str | None) -> dict[str, dict[str, str]]:
    result: dict[str, dict[str, str]] = {}
    for start in range(0, len(arns), 20):  # describe-tags accepts 20 ARNs
        batch = arns[start : start + 20]
        data = aws(["elbv2", "describe-tags", "--resource-arns", *batch], region, profile)
        for description in data.get("TagDescriptions", []):
            result[description["ResourceArn"]] = as_tags(description.get("Tags"))
    return result


def vpc_resources(vpc_id: str, region: str, profile: str | None) -> list[dict[str, Any]]:
    """Security groups, rules, load balancers, listeners and target groups inside the project VPC."""
    items: list[dict[str, Any]] = []
    groups = aws(["ec2", "describe-security-groups", "--filters", f"Name=vpc-id,Values={vpc_id}"], region, profile)
    group_names: dict[str, str] = {}
    for group in groups.get("SecurityGroups", []):
        group_names[group["GroupId"]] = group.get("GroupName", "")
        items.append(
            {
                "arn": group["GroupId"],
                "type": "ec2:security-group",
                "name": group.get("GroupName"),
                "tags": as_tags(group.get("Tags")),
            }
        )
    if group_names:
        rules = aws(
            ["ec2", "describe-security-group-rules", "--filters", f"Name=group-id,Values={','.join(group_names)}"],
            region,
            profile,
        )
        for rule in rules.get("SecurityGroupRules", []):
            items.append(
                {
                    "arn": rule["SecurityGroupRuleId"],
                    "type": "ec2:security-group-rule",
                    "name": group_names.get(rule["GroupId"]),
                    "tags": as_tags(rule.get("Tags")),
                    "detail": {
                        "direction": "egress" if rule.get("IsEgress") else "ingress",
                        "protocol": rule.get("IpProtocol"),
                        "ports": f"{rule.get('FromPort')}-{rule.get('ToPort')}",
                    },
                }
            )
    balancers = [
        lb
        for lb in aws(["elbv2", "describe-load-balancers"], region, profile).get("LoadBalancers", [])
        if lb.get("VpcId") == vpc_id
    ]
    target_groups = [
        tg
        for tg in aws(["elbv2", "describe-target-groups"], region, profile).get("TargetGroups", [])
        if tg.get("VpcId") == vpc_id
    ]
    listeners: list[dict[str, Any]] = []
    for lb in balancers:
        listeners += aws(
            ["elbv2", "describe-listeners", "--load-balancer-arn", lb["LoadBalancerArn"]], region, profile
        ).get("Listeners", [])
    arns = [lb["LoadBalancerArn"] for lb in balancers]
    arns += [tg["TargetGroupArn"] for tg in target_groups] + [ln["ListenerArn"] for ln in listeners]
    tags = elb_tags(arns, region, profile) if arns else {}
    for lb in balancers:
        arn = lb["LoadBalancerArn"]
        items.append(
            {
                "arn": arn,
                "type": "elasticloadbalancing:loadbalancer",
                "name": lb["LoadBalancerName"],
                "tags": tags.get(arn, {}),
            }
        )
    for tg in target_groups:
        arn = tg["TargetGroupArn"]
        items.append(
            {
                "arn": arn,
                "type": "elasticloadbalancing:targetgroup",
                "name": tg["TargetGroupName"],
                "tags": tags.get(arn, {}),
            }
        )
    for ln in listeners:
        arn = ln["ListenerArn"]
        detail = {"port": ln.get("Port"), "protocol": ln.get("Protocol")}
        items.append(
            {
                "arn": arn,
                "type": "elasticloadbalancing:listener",
                "name": None,
                "tags": tags.get(arn, {}),
                "detail": detail,
            }
        )
    return items


def check(resources: list[dict[str, Any]], a: argparse.Namespace) -> list[dict[str, str]]:
    """Findings for every resource of this project. Security group rules are listed, not tag-checked: the
    template resources that create them cannot carry tags (the group, which does, is checked)."""
    pattern = name_pattern(a.region_code, a.context, a.env)
    findings: list[dict[str, str]] = []
    for item in resources:
        if item["type"] == "ec2:security-group-rule" or item["name"] == "default":
            continue  # the default group is created by AWS with the VPC
        problems = tag_problems(item["tags"], a.env, a.repo_name)
        name = item["name"]
        if name and not name_is_valid(name, pattern):
            problems.append(f"name {name} breaks the pattern")
        findings += [{"type": item["type"], "resource": item["arn"], "problem": p} for p in problems]
    return findings


def build_report(a: argparse.Namespace) -> dict[str, Any]:
    resources = tagged_resources(a)
    vpc = vpc_id_of(resources)
    seen = {item["arn"] for item in resources}
    if vpc:
        resources += [item for item in vpc_resources(vpc, a.region, a.profile) if item["arn"] not in seen]
    counts: dict[str, int] = {}
    for item in resources:
        counts[item["type"]] = counts.get(item["type"], 0) + 1
    return {
        "environment": a.env,
        "repository": a.repo_name,
        "vpc": vpc,
        "counts": dict(sorted(counts.items())),
        "resources": resources,
        "findings": check(resources, a),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--env", required=True, choices=["dev", "prod"])
    parser.add_argument("--region", default="us-east-2")
    parser.add_argument("--region-code", default="useast2")
    parser.add_argument("--context", default="oecalc")
    parser.add_argument("--repo-name", default=REPO_NAME)
    parser.add_argument("--profile", default=None)
    parser.add_argument("--output", type=Path, default=None, help="JSON file with the full inventory")
    args = parser.parse_args(argv)
    try:
        report = build_report(args)
    except ReadError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    if args.output:
        args.output.write_bytes((json.dumps(report, indent=2) + "\n").encode("utf-8"))
    print(f"{len(report['resources'])} resources in {args.env} (VPC {report['vpc'] or 'not found'})")
    for kind, count in report["counts"].items():
        print(f"  {kind}: {count}")
    for finding in report["findings"]:
        print(f"FINDING {finding['type']} {finding['resource']}: {finding['problem']}")
    print(f"{len(report['findings'])} findings")
    return 1 if report["findings"] else 0


if __name__ == "__main__":
    sys.exit(main())
